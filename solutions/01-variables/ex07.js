/**
 * Exercise 07 · Counting up and down
 *
 * `x++` adds 1 to x. `x--` subtracts 1 from x.
 *
 * Task:
 *   1. The player lost a life: decrease `lives` by one using --.
 *   2. The player beat two levels: increase `level` twice using ++.
 */

export let lives = 3;
export let level = 1;

lives--;
level++;
level++;
